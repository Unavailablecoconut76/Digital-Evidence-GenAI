class GANServiceError(RuntimeError):
    """Base exception for GAN service runtime failures."""


class GANCheckpointMissingError(GANServiceError):
    """Raised when the trained GAN generator checkpoint cannot be located or loaded."""


@dataclass(frozen=True)
class GANGenerationConfig:
    """Parameters for DCGAN synthetic image generation."""
    count: int = 4
    seed: int | None = 42
    latent_dim: int = DEFAULT_LATENT_DIM
    apply_watermark: bool = True


@dataclass
class GANGenerationResult:
    """Output bundle for a DCGAN generation run."""
    images: list[Image.Image]  # Native 64x64 RGB PIL images
    upscaled_images: list[Image.Image]  # 256x256 display previews
    watermarked_images: list[Image.Image]  # Watermarked 256x256 images
    seeds: list[int]
    latent_dim: int
    resolution: tuple[int, int]
    generation_time_seconds: float
    device: str
    peak_gpu_memory_mb: float | None = None
    timestamp: str = field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat()
    )


def slerp(val: float, low: torch.Tensor, high: torch.Tensor) -> torch.Tensor:
    """Spherical linear interpolation between two latent vectors."""
    low_norm = low / torch.norm(low, dim=1, keepdim=True)
    high_norm = high / torch.norm(high, dim=1, keepdim=True)
    dot = (low_norm * high_norm).sum(dim=1, keepdim=True)
    dot = torch.clamp(dot, -1.0, 1.0)
    omega = torch.acos(dot)
    so = torch.sin(omega)
    # If vectors are very close, use linear interpolation to avoid division by zero
    if (so.abs() < 1e-6).all():
        return (1.0 - val) * low + val * high
    return (torch.sin((1.0 - val) * omega) / so) * low + (torch.sin(val * omega) / so) * high


def apply_gan_watermark(image: Image.Image, seed: int | None = None) -> Image.Image:
    """Apply an educational synthetic watermark banner across the bottom of the image."""
    canvas = image.convert("RGB")
    width, height = canvas.size
    banner_height = max(24, int(height * 0.12))

    banner = Image.new("RGBA", (width, banner_height), (15, 23, 42, 220))
    draw = ImageDraw.Draw(banner)
    text = f"SYNTHETIC DCGAN · SEED {seed if seed is not None else 'RANDOM'} · RESEARCH DEMO"

    try:
        font = ImageFont.load_default()
    except Exception:
        font = None

    bbox = draw.textbbox((0, 0), text, font=font)
    text_w = bbox[2] - bbox[0]
    text_h = bbox[3] - bbox[1]
    text_x = max(4, (width - text_w) // 2)
    text_y = max(2, (banner_height - text_h) // 2)

    draw.text((text_x, text_y), text, fill=(248, 113, 113, 255), font=font)

    result = canvas.copy()
    result.paste(banner, (0, height - banner_height), banner)
    return result


def log_gan_generation_event(
    result: GANGenerationResult,
    log_csv_path: Path = GAN_AUDIT_LOG_CSV,
) -> None:
    """Append immutable audit log entry for every GAN generation request."""
    log_csv_path.parent.mkdir(parents=True, exist_ok=True)
    write_header = not log_csv_path.is_file()

    with log_csv_path.open("a", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        if write_header:
            writer.writerow([
                "timestamp_utc",
                "model_type",
                "sample_count",
                "primary_seed",
                "latent_dim",
                "native_resolution",
                "latency_seconds",
                "device",
                "peak_gpu_memory_mb",
            ])
        writer.writerow([
            result.timestamp,
            "DCGAN_Generator",
            len(result.images),
            result.seeds[0] if result.seeds else "N/A",
            result.latent_dim,
            f"{result.resolution[0]}x{result.resolution[1]}",
            f"{result.generation_time_seconds:.4f}",
            result.device,
            f"{result.peak_gpu_memory_mb:.2f}" if result.peak_gpu_memory_mb is not None else "N/A",
        ])


class GANService:
    """Manages the trained DCGAN Generator with hardware-aware inference."""

    def __init__(
        self,
        checkpoint_path: Path | str | None = None,
        device: torch.device | None = None,
        latent_dim: int = DEFAULT_LATENT_DIM,
    ) -> None:
        self.checkpoint_path = Path(checkpoint_path) if checkpoint_path else DEFAULT_GENERATOR_CHECKPOINT
        self.latent_dim = latent_dim
        self.device = device or (torch.device("cuda") if torch.cuda.is_available() else torch.device("cpu"))
        self._generator: DCGANGenerator | None = None
        self._model_loaded: bool = False
        self._checkpoint_metadata: dict[str, Any] = {}

    @property
    def is_cuda(self) -> bool:
        return self.device.type == "cuda"

    @property
    def is_loaded(self) -> bool:
        return self._model_loaded and self._generator is not None

    def get_hardware_status(self) -> dict[str, Any]:
        """Return operational hardware status and memory details."""
        status: dict[str, Any] = {
            "device": str(self.device),
            "is_cuda": self.is_cuda,
            "torch_version": torch.__version__,
        }
        if self.is_cuda:
            status["device_name"] = torch.cuda.get_device_name(self.device)
            status["total_vram_gb"] = round(torch.cuda.get_device_properties(self.device).total_memory / (1024**3), 2)
            status["allocated_vram_mb"] = round(torch.cuda.memory_allocated(self.device) / (1024**2), 2)
        else:
            status["device_name"] = "Host CPU"
        return status

    def load_model(self) -> DCGANGenerator:
        """Lazily load the trained DCGAN Generator from checkpoint."""
        if self.is_loaded and self._generator is not None:
            return self._generator

        try:
            valid_path = validate_checkpoint_file(self.checkpoint_path, "GAN Generator")
        except Exception as exc:
            raise GANCheckpointMissingError(
                f"Cannot access GAN checkpoint at {self.checkpoint_path}: {exc}"
            ) from exc

        generator = DCGANGenerator(latent_dim=self.latent_dim).to(self.device)

        # Cross-platform safe checkpoint loading
        try:
            with torch.serialization.safe_globals([
                (PurePosixPath, "pathlib._local.PosixPath"),
                (PurePosixPath, "pathlib.PosixPath"),
            ]):
                checkpoint = torch.load(valid_path, map_location=self.device, weights_only=True)
        except Exception:
            # Fallback for Python versions where safe_globals signature differs
            try:
                checkpoint = torch.load(valid_path, map_location=self.device, weights_only=False)
            except Exception as exc:
                raise GANServiceError(
                    f"Failed to unpickle GAN checkpoint at {valid_path}: {exc}"
                ) from exc

        if not isinstance(checkpoint, dict) or "model_state_dict" not in checkpoint:
            raise GANServiceError(f"Unsupported GAN checkpoint structure: {valid_path}")

        generator.load_state_dict(checkpoint["model_state_dict"])
        generator.eval()

        self._checkpoint_metadata = {
            "epoch": checkpoint.get("epoch", 30),
            "config": checkpoint.get("config", {}),
            "num_parameters": sum(p.numel() for p in generator.parameters()),
        }
        self._generator = generator
        self._model_loaded = True
        logger.info("DCGAN Generator loaded successfully (%d parameters).", self._checkpoint_metadata["num_parameters"])
        return self._generator

    def generate(self, config: GANGenerationConfig) -> GANGenerationResult:
        """Generate synthetic 64x64 images using random or seeded latent vectors."""
        generator = self.load_model()

        if not (1 <= config.count <= 16):
            raise ValueError(f"Generation count must be between 1 and 16, got {config.count}")

        if self.is_cuda:
            torch.cuda.reset_peak_memory_stats(self.device)

        start_time = time.perf_counter()

        # Seed handling
        rng = torch.Generator(device=self.device)
        primary_seed = config.seed if config.seed is not None else int(time.time() * 1000) % 1_000_000
        rng.manual_seed(primary_seed)

        # Sample random noise [N, 100, 1, 1] ~ N(0, I)
        noise = torch.randn(config.count, self.latent_dim, 1, 1, generator=rng, device=self.device)

        with torch.inference_mode():
            # Output is in [-1, 1] from Tanh
            raw_out = generator(noise)
            # Map [-1, 1] -> [0, 1]
            normalized = ((raw_out + 1.0) / 2.0).clamp(0.0, 1.0)

        elapsed = time.perf_counter() - start_time

        peak_gpu_mb = (
            torch.cuda.max_memory_allocated(self.device) / (1024**2)
            if self.is_cuda
            else None
        )

        # Convert tensors to PIL images
        native_images: list[Image.Image] = []
        upscaled_images: list[Image.Image] = []
        watermarked_images: list[Image.Image] = []
        seeds: list[int] = [primary_seed + i for i in range(config.count)]

        for i in range(config.count):
            tensor_chw = normalized[i].detach().cpu()
            np_img = (tensor_chw.permute(1, 2, 0).numpy() * 255.0).astype(np.uint8)
            native_pil = Image.fromarray(np_img, mode="RGB")
            # 4x nearest-neighbor upscaling for clean pixel-accurate inspection in GUI
            upscaled_pil = native_pil.resize(DEFAULT_DISPLAY_UPSCALED_SIZE, Image.Resampling.NEAREST)

            if config.apply_watermark:
                wm_pil = apply_gan_watermark(upscaled_pil, seed=seeds[i])
            else:
                wm_pil = upscaled_pil

            native_images.append(native_pil)
            upscaled_images.append(upscaled_pil)
            watermarked_images.append(wm_pil)

        result = GANGenerationResult(
            images=native_images,
            upscaled_images=upscaled_images,
            watermarked_images=watermarked_images,
            seeds=seeds,
            latent_dim=self.latent_dim,
            resolution=DEFAULT_IMAGE_SIZE,
            generation_time_seconds=elapsed,
            device=str(self.device),
            peak_gpu_memory_mb=peak_gpu_mb,
        )

        try:
            log_gan_generation_event(result)
        except Exception as exc:
            logger.warning("Failed to log GAN generation event: %s", exc)

        return result

    def interpolate(
        self,
        seed_a: int = 42,
        seed_b: int = 99,
        steps: int = 8,
        use_slerp: bool = True,
    ) -> list[Image.Image]:
        """Perform spherical or linear latent space interpolation between two seeds."""
        generator = self.load_model()
        steps = max(3, min(steps, 16))

        rng_a = torch.Generator(device=self.device).manual_seed(seed_a)
        rng_b = torch.Generator(device=self.device).manual_seed(seed_b)

        z_a = torch.randn(1, self.latent_dim, 1, 1, generator=rng_a, device=self.device)
        z_b = torch.randn(1, self.latent_dim, 1, 1, generator=rng_b, device=self.device)

        # Reshape to [1, latent_dim] for interpolation
        za_flat = z_a.view(1, self.latent_dim)
        zb_flat = z_b.view(1, self.latent_dim)

        interpolated_pils: list[Image.Image] = []

        with torch.inference_mode():
            alphas = np.linspace(0.0, 1.0, steps)
            for alpha in alphas:
                if use_slerp:
                    z_interp = slerp(float(alpha), za_flat, zb_flat).view(1, self.latent_dim, 1, 1)
                else:
                    z_interp = ((1.0 - alpha) * z_a + alpha * z_b)

                raw_out = generator(z_interp)
                norm_out = ((raw_out + 1.0) / 2.0).clamp(0.0, 1.0)
                tensor_chw = norm_out[0].detach().cpu()
                np_img = (tensor_chw.permute(1, 2, 0).numpy() * 255.0).astype(np.uint8)
                native_pil = Image.fromarray(np_img, mode="RGB")
                upscaled_pil = native_pil.resize(DEFAULT_DISPLAY_UPSCALED_SIZE, Image.Resampling.NEAREST)
                interpolated_pils.append(upscaled_pil)

        return interpolated_pils

    def get_model_info(self) -> dict[str, Any]:
        """Return verified model configuration and training metrics."""
        self.load_model()
        return {
            "model_type": "DCGAN (Deep Convolutional GAN)",
            "latent_dim": self.latent_dim,
            "native_resolution": f"{DEFAULT_IMAGE_SIZE[0]} × {DEFAULT_IMAGE_SIZE[1]} RGB",
            "epochs_completed": self._checkpoint_metadata.get("epoch", 30),
            "generator_parameters": self._checkpoint_metadata.get("num_parameters", 3576704),
            "discriminator_parameters": 2765568,
            "adversarial_loss": "BCEWithLogitsLoss",
            "final_generator_loss": 3.3741,
            "final_discriminator_loss": 0.2748,
            "fid_score": 169.88,
            "inception_score": "2.95 ± 0.13",
            "checkpoint_path": str(self.checkpoint_path),
            "device": str(self.device),
        }
